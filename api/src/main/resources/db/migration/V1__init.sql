-- Users sign in with GitHub (github_id) or, in development only, by login name.
create table users (
    id          bigint generated by default as identity primary key,
    github_id   bigint unique,
    login       varchar(100) not null unique,
    name        varchar(200),
    avatar_url  varchar(500),
    created_at  timestamptz not null default now()
);

-- An agent is a thing being evaluated. Its API key is stored only as a SHA-256 hash.
create table agents (
    id              bigint generated by default as identity primary key,
    owner_id        bigint not null references users (id) on delete cascade,
    name            varchar(100) not null,
    description     varchar(500),
    api_key_prefix  varchar(16) not null,
    api_key_hash    char(64) not null unique,
    created_at      timestamptz not null default now(),
    unique (owner_id, name)
);

-- One eval run. Summary metrics are denormalized for fast dashboard queries.
create table runs (
    id              bigint generated by default as identity primary key,
    agent_id        bigint not null references agents (id) on delete cascade,
    external_id     varchar(64) not null,
    label           varchar(200) not null,
    agent_kind      varchar(50),
    model           varchar(200),
    extract_model   varchar(200),
    git_sha         varchar(64),
    git_branch      varchar(200),
    tasks           integer not null,
    passed          integer not null,
    success_rate    double precision not null,
    field_accuracy  double precision,
    avg_steps       double precision not null,
    p50_seconds     double precision not null,
    p95_seconds     double precision not null,
    input_tokens    bigint not null,
    output_tokens   bigint not null,
    total_cost_usd  double precision,
    created_at      timestamptz not null default now(),
    unique (agent_id, external_id)
);
create index runs_agent_created_idx on runs (agent_id, created_at desc);

create table task_results (
    id              bigint generated by default as identity primary key,
    run_id          bigint not null references runs (id) on delete cascade,
    task_id         varchar(100) not null,
    kind            varchar(50) not null,
    vendor          varchar(50) not null,
    difficulty      varchar(20) not null,
    passed          boolean not null,
    failure         varchar(50),
    detail          text,
    answer          text,
    field_accuracy  double precision,
    steps           integer not null,
    replans         integer not null default 0,
    seconds         double precision not null,
    input_tokens    bigint not null,
    output_tokens   bigint not null,
    cost_usd        double precision,
    unique (run_id, task_id)
);

create table steps (
    id              bigint generated by default as identity primary key,
    task_result_id  bigint not null references task_results (id) on delete cascade,
    step_no         integer not null,
    action          varchar(50),
    args            text,
    thought         text,
    outcome         text,
    ok              boolean,
    verified        boolean,
    feedback        text,
    url             varchar(2000),
    screenshot      varchar(200)
);
create index steps_task_result_idx on steps (task_result_id, step_no);
